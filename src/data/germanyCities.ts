export interface DERestaurant {
  name: string;
  address: string;
  hours: string;
  phone: string;
  website: string;
  directionsUrl: string;
  specialty: string;
  overview: string;
  menuHighlights: string[];
  proTip: string;
  icon: string;
  featured: boolean;
  cuisineTypes: string[];
  celiacSafe: "protocols-in-place" | "dedicated-facility";
  menuType: "mixed-menu" | "fully-gluten-free";
  rating: number;
  reviewCount: number;
  nearby?: { label: string; name: string; href?: string }[];
}

export interface DECity {
  name: string;
  slug: string;
  restaurants: DERestaurant[];
}

export const deSlug = (name: string) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const mapsUrl = (name: string, address: string) =>
  `https://maps.google.com/?q=${encodeURIComponent(`${name}, ${address}`)}`;

export const findDERestaurant = (citySlug: string, restaurantSlug: string) => {
  const city = germanyCities.find((c) => c.slug === citySlug);
  if (!city) return undefined;
  const restaurant = city.restaurants.find((r) => deSlug(r.name) === restaurantSlug);
  return restaurant ? { city, restaurant } : undefined;
};

